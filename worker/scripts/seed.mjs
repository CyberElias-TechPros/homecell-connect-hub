#!/usr/bin/env node
/**
 * Seed a local (or remote) D1 database with one working cell.
 *
 * Everything this creates is an *example* organisation, not church policy.
 * District / area / zone names, meeting times and the welcome message are all
 * ordinary data that a leader edits from the app — nothing about how a real
 * Loveworld / Christ Embassy structure must be named is baked in here.
 *
 * Passwords are hashed with the same PBKDF2-HMAC-SHA256 parameters the Worker
 * uses, so the seeded accounts can log in normally.
 *
 *   node worker/scripts/seed.mjs              # local
 *   node worker/scripts/seed.mjs --remote     # deployed database
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { webcrypto as crypto } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const WORKER_DIR = resolve(HERE, '..');
const REMOTE = process.argv.includes('--remote');
/** Wipe every table before seeding, so a test run starts from a known state. */
const RESET = process.argv.includes('--reset');

/**
 * Deletion order matters: children before parents. Listed explicitly rather
 * than discovered, so a new table that is added later must be considered here
 * deliberately instead of being silently left behind.
 */
const TABLES_IN_DELETION_ORDER = [
  'consent_records',
  'notifications',
  'testimonies',
  'prayer_requests',
  'follow_up_notes',
  'follow_ups',
  'attendance_records',
  'weekly_reports',
  'announcement_reads',
  'announcements',
  'material_acks',
  'materials',
  'invitations',
  'sessions',
  'audit_logs',
  'rate_limits',
  'users',
  'homecells',
  'zones',
  'areas',
  'districts',
  'organizations',
];

const ITERATIONS = 100_000;

function toBase64(bytes) {
  return Buffer.from(bytes).toString('base64');
}

async function hashPassword(password, salt) {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey('raw', enc.encode(password), { name: 'PBKDF2' }, false, [
    'deriveBits',
  ]);
  const bits = await crypto.subtle.deriveBits(
    { name: 'PBKDF2', salt: enc.encode(salt), iterations: ITERATIONS, hash: 'SHA-256' },
    key,
    256,
  );
  return toBase64(new Uint8Array(bits));
}

function randomSalt() {
  const buf = new Uint8Array(16);
  crypto.getRandomValues(buf);
  return toBase64(buf);
}

/** Single-quote escaping for SQL literals. */
function q(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

const NOW = '2026-01-01T00:00:00Z';

